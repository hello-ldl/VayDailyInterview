import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.join(__dirname, '..')
const CHUNK_DIR = path.join(ROOT, 'public', 'questions', 'chunks')

// 修复特定题目的答案
function fixSpecificAnswers() {
  const files = fs.readdirSync(CHUNK_DIR)
    .filter(f => f.endsWith('.json'))
    .sort()

  for (const file of files) {
    const filePath = path.join(CHUNK_DIR, file)
    let content = fs.readFileSync(filePath, 'utf8')

    // 检查是否包含需要修复的答案
    if (content.includes('架构设计需要权衡各种因素')) {
      console.log(`Fixing ${file}...`)

      // 替换特定的答案模式
      content = content.replace(
        /"answer": "针对系统架构问题：([^"]*常见误区[^"]*)\n\n详细解答：\n\n架构设计需要权衡各种因素\.\n\n([^"]*)"/g,
        (match, title, prompt) => {
          const newAnswer = generateCommonPitfallsAnswer(title.trim(), prompt.trim())
          return `"answer": ${JSON.stringify(newAnswer)}`
        }
      )

      content = content.replace(
        /"answer": "针对系统架构问题：([^"]*何时应该优先使用[^"]*)\n\n详细解答：\n\n架构设计需要权衡各种因素\.\n\n([^"]*)"/g,
        (match, title, prompt) => {
          const newAnswer = generateWhenToUseAnswer(title.trim(), prompt.trim())
          return `"answer": ${JSON.stringify(newAnswer)}`
        }
      )

      content = content.replace(
        /"answer": "针对系统架构问题：([^"]*核心是什么[^"]*)\n\n详细解答：\n\n架构设计需要权衡各种因素\.\n\n([^"]*)"/g,
        (match, title, prompt) => {
          const newAnswer = generateCoreConceptAnswer(title.trim(), prompt.trim())
          return `"answer": ${JSON.stringify(newAnswer)}`
        }
      )

      content = content.replace(
        /"answer": "针对系统架构问题：([^"]*区别是什么[^"]*)\n\n详细解答：\n\n架构设计需要权衡各种因素\.\n\n([^"]*)"/g,
        (match, title, prompt) => {
          const newAnswer = generateDifferenceAnswer(title.trim(), prompt.trim())
          return `"answer": ${JSON.stringify(newAnswer)}`
        }
      )

      fs.writeFileSync(filePath, content, 'utf8')
      console.log(`Fixed answers in ${file}`)
    }
  }
}

function generateFixedAnswer(title, prompt) {
  // 架构设计相关题目
  if (title.includes('常见误区')) {
    return generateCommonPitfallsAnswer(title, prompt)
  } else if (title.includes('何时应该优先使用') || title.includes('何时优先使用')) {
    return generateWhenToUseAnswer(title, prompt)
  } else if (title.includes('核心是什么')) {
    return generateCoreConceptAnswer(title, prompt)
  } else if (title.includes('区别是什么')) {
    return generateDifferenceAnswer(title, prompt)
  } else {
    return generateGeneralArchitectureAnswer(title, prompt)
  }
}

